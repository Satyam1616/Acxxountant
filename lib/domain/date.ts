import { DomainError } from "./errors";

export function isValidBusinessDate(value: string): boolean {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  const [year, month, day] = value.split("-").map(Number);
  const date = new Date(Date.UTC(year, month - 1, day));
  return (
    date.getUTCFullYear() === year && date.getUTCMonth() === month - 1 && date.getUTCDate() === day
  );
}

export function assertBusinessDate(value: string, code = "invalid_date"): void {
  if (!isValidBusinessDate(value)) throw new DomainError(code, `Invalid calendar date: ${value}`);
}

export function todayInTimeZone(timeZone = "UTC"): string {
  try {
    const parts = new Intl.DateTimeFormat("en-CA", {
      timeZone,
      year: "numeric",
      month: "2-digit",
      day: "2-digit",
    }).formatToParts(new Date());
    const values = Object.fromEntries(parts.map((part) => [part.type, part.value]));
    const date = `${values.year}-${values.month}-${values.day}`;
    if (isValidBusinessDate(date)) return date;
  } catch {
    // Fall back to UTC when an administrator has configured an invalid zone.
  }
  return new Date().toISOString().slice(0, 10);
}

export function isValidTimeZone(value: string): boolean {
  try {
    new Intl.DateTimeFormat("en-US", { timeZone: value }).format();
    return true;
  } catch {
    return false;
  }
}
